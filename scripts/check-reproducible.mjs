/**
 * Can git reproduce what we are about to deploy?
 *
 * A deploy here uploads the WORKING TREE - Vercel is not wired to GitHub - so the bytes
 * on disk under public/ are the bytes served. That makes git a record of the deliverable,
 * and the record has to be exact.
 *
 * On 13 November 2026 it was not. The AI Act browser app had been live since 7 October
 * from four files no commit recorded, and `core.autocrlf=true` with no .gitattributes
 * meant a fresh checkout rewrote the bundles with CRLF, so a clone could not reproduce
 * the deployed site at all. A `git clean -fd` or a fresh clone plus a deploy would have
 * silently served the August build. Nothing went red for 37 days.
 *
 * It was not even unseen. `review/store-copy-audit-20261030/aiact-matches-live.mjs` was
 * written on 30 October and names the uncommitted files in its own first comment, and the
 * release runbook then recorded them as an acceptable state. That guard compares DISK to
 * LIVE and passes. It is structurally incapable of asking whether GIT can reproduce DISK,
 * which is where the hazard lives. This script is the missing direction. The two are
 * complements, not alternatives: run both.
 *
 * Three checks, and the third is the one that makes the other two worth believing:
 *   1. Nothing under public/ is untracked or modified. Untracked here is ALREADY LIVE.
 *   2. Every tracked file under public/ comes back byte-identical from `git checkout-index`,
 *      so a clean clone reproduces the deployed bytes.
 *   3. SELF-TEST: the comparator is shown to detect a one-byte change before any clean
 *      result is reported. A check that has only ever passed has not been shown able to
 *      fail.
 *
 * WHAT THIS LEG DOES NOT PROVE, found by testing it against the real pre-fix commit
 * rather than by reasoning about it. Checks 1 and 2 compare the INDEX to the WORKING
 * TREE. That is internal consistency, not fidelity to production. Measured in a detached
 * worktree at 82b5b10, the commit before the fix: with no .gitattributes, git checked the
 * bundles out WITH CRLF, so disk and checkout-index agreed at 41 CR bytes each and this
 * check would have passed - while the bytes actually live were the LF ones. A freshly
 * cloned tree can be perfectly self-consistent and still deploy something production has
 * never seen.
 *
 * So the useful property is transitive and needs BOTH legs:
 *     index == disk   (--git, this file, free and offline)
 *   + disk  == live   (--live, this file, network)
 *   => index == live  - a clone reproduces what the world is being served.
 * Run with no flag to get both. Neither leg alone is sufficient, and the disk == live leg
 * on its own is the one that was already being run on 30 October while the defect sat
 * there for another fortnight.
 *
 * Usage:  npm run apps:check-reproducible            both legs
 *         node scripts/check-reproducible.mjs --git  index vs disk only, no network
 *         node scripts/check-reproducible.mjs --live disk vs live only
 * Exit 0 = reproducible. Exit 1 = a real finding. Exit 2 = the check itself is broken.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const siteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SCOPE = 'public';

/** Live leg scope: the built browser-app bundles. These are the files that are copied in
 *  rather than generated by the Astro build, so they are the ones that can silently drift.
 *  Everything else under public/ is small, hand-authored and visible in review. */
const LIVE_SCOPE = /^public\/[^/]+\/app\//;
const ORIGIN = 'https://www.oxenwaldt.com';
const LIVE_CONCURRENCY = 8;

const argv = process.argv.slice(2);
const runGit = !argv.includes('--live') || argv.includes('--git');
const runLive = !argv.includes('--git') || argv.includes('--live');

const git = (...args) =>
  execFileSync('git', args, { cwd: siteRoot, encoding: 'utf8', maxBuffer: 1 << 28 });

const sha = (buf) => createHash('sha256').update(buf).digest('hex');

/** Hash from a Buffer, never by handing a path to an external tool: a Windows path
 *  passed to sha256sum breaks the compare and makes everything look like a mismatch. */
const hashFile = (file) => sha(fs.readFileSync(file));

let tmp;
const cleanup = () => {
  if (tmp && fs.existsSync(tmp)) fs.rmSync(tmp, { recursive: true, force: true });
};

try {
  const tracked = git('ls-files', '-z', '--', SCOPE).split('\0').filter(Boolean);
  if (tracked.length === 0) {
    console.error(`check-reproducible: no tracked files under ${SCOPE}/. That is not a`);
    console.error('clean result, it means this check looked in the wrong place.');
    process.exit(2);
  }

  const dirty = [];
  const differing = [];
  const missing = [];

  if (runGit) {
    // ---- 1. Working tree clean under the deployed scope ----------------------------
    dirty.push(...git('status', '--porcelain', '--', SCOPE).split('\n').filter(Boolean));

    // ---- 2. Reproduce every tracked file from the index ----------------------------
    tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'oxw-repro-'));
    git('checkout-index', '-a', `--prefix=${tmp.replace(/\\/g, '/')}/`);

    for (const rel of tracked) {
      const fromIndex = path.join(tmp, rel);
      const onDisk = path.join(siteRoot, rel);
      if (!fs.existsSync(fromIndex)) { missing.push(rel); continue; }
      if (hashFile(fromIndex) !== hashFile(onDisk)) differing.push(rel);
    }

    // ---- 3. Self-test, BEFORE reporting anything clean -----------------------------
    // Corrupt one checked-out copy by a single byte and confirm the comparator notices.
    // Without this, "0 differing" could simply mean the comparator cannot say otherwise.
    const probe = path.join(tmp, tracked[0]);
    const original = fs.readFileSync(probe);
    fs.writeFileSync(probe, Buffer.concat([original, Buffer.from('x')]));
    const comparatorWorks = hashFile(probe) !== hashFile(path.join(siteRoot, tracked[0]));
    fs.writeFileSync(probe, original);

    if (!comparatorWorks) {
      console.error('check-reproducible: SELF-TEST FAILED. The comparator called a file');
      console.error('identical after a byte was appended to it, so no result below can be');
      console.error('trusted. Fix the check before trusting any pass.');
      process.exit(2);
    }
  }

  // ---- 4. Live leg: does disk equal what the world is being served? ------------------
  const liveDiffer = [];
  const liveMissing = [];
  let liveChecked = 0;
  let liveControlPassed = false;

  if (runLive) {
    const liveFiles = tracked.filter((f) => LIVE_SCOPE.test(f));

    // Positive control FIRST, on a URL that must not exist. If this comes back 200 the
    // host is answering everything and a clean result below would mean nothing.
    const controlRes = await fetch(`${ORIGIN}/__no-such-file-control-${Date.now()}.js`)
      .catch(() => null);
    liveControlPassed = controlRes != null && controlRes.status === 404;
    if (!liveControlPassed) {
      console.error('check-reproducible: LIVE CONTROL FAILED. A URL that cannot exist did');
      console.error(`not return 404 (got ${controlRes ? controlRes.status : 'no response'}).`);
      console.error('The live comparison cannot be trusted, so it is not reported.');
      process.exit(2);
    }

    const queue = [...liveFiles];
    const worker = async () => {
      for (;;) {
        const rel = queue.shift();
        if (!rel) return;
        const url = `${ORIGIN}/${rel.slice(`${SCOPE}/`.length)}`;
        try {
          const res = await fetch(url);
          if (!res.ok) { liveMissing.push(`${rel} (HTTP ${res.status})`); continue; }
          const live = Buffer.from(await res.arrayBuffer());
          if (sha(live) !== hashFile(path.join(siteRoot, rel))) liveDiffer.push(rel);
          liveChecked += 1;
        } catch (e) {
          liveMissing.push(`${rel} (${e && e.message})`);
        }
      }
    };
    await Promise.all(Array.from({ length: LIVE_CONCURRENCY }, worker));
  }

  // ---- Report -----------------------------------------------------------------------
  const gitProblems = runGit && (dirty.length || differing.length || missing.length);
  const liveProblems = runLive && (liveDiffer.length || liveMissing.length);

  if (!gitProblems && !liveProblems) {
    if (runGit) {
      console.log(
        `index == disk: ${tracked.length} tracked files under ${SCOPE}/ are byte-identical ` +
        'to the working tree, nothing untracked or modified. ' +
        '(Self-test passed: a one-byte change is detected.)'
      );
    }
    if (runLive) {
      console.log(
        `disk == live: ${liveChecked} built app files match what ${ORIGIN} serves. ` +
        '(Control passed: a non-existent URL returns 404.)'
      );
    }
    if (runGit && runLive) {
      console.log('=> index == live. A clean clone reproduces what the world is served.');
    } else {
      console.log('One leg only: this does NOT establish that a clone reproduces live.');
    }
    process.exit(0);
  }

  console.error('GIT CANNOT REPRODUCE WHAT WOULD BE DEPLOYED.\n');

  if (dirty.length) {
    console.error(`Untracked or modified under ${SCOPE}/ (${dirty.length}).`);
    console.error('These go live with the next deploy and no commit records them. A');
    console.error('git clean -fd or a fresh clone would silently revert them:');
    for (const line of dirty.slice(0, 40)) console.error(`  ${line}`);
    if (dirty.length > 40) console.error(`  ... and ${dirty.length - 40} more`);
    console.error('');
  }

  if (differing.length) {
    console.error(`Checked out differently from disk (${differing.length}).`);
    console.error('A clone would not reproduce these bytes. The usual cause is');
    console.error('core.autocrlf with nothing in .gitattributes governing the path;');
    console.error('the at-risk set is what this prints:');
    console.error('  git ls-files --eol -- <path> | awk \'$1=="i/lf" && $2=="w/lf" && $3=="attr/"\'');
    for (const rel of differing.slice(0, 40)) console.error(`  ${rel}`);
    if (differing.length > 40) console.error(`  ... and ${differing.length - 40} more`);
    console.error('');
  }

  if (missing.length) {
    console.error(`Tracked but absent from the checkout (${missing.length}):`);
    for (const rel of missing.slice(0, 40)) console.error(`  ${rel}`);
    console.error('');
  }

  if (liveDiffer.length) {
    console.error(`On disk but DIFFERENT from what is served live (${liveDiffer.length}).`);
    console.error('A deploy from this tree would change these files for every visitor:');
    for (const rel of liveDiffer.slice(0, 40)) console.error(`  ${rel}`);
    if (liveDiffer.length > 40) console.error(`  ... and ${liveDiffer.length - 40} more`);
    console.error('');
  }

  if (liveMissing.length) {
    console.error(`Could not be read from the live site (${liveMissing.length}):`);
    for (const rel of liveMissing.slice(0, 40)) console.error(`  ${rel}`);
    console.error('');
  }

  console.error('A git finding here is about reproducibility, not necessarily a broken');
  console.error('site: the live site may be serving exactly these bytes right now. That is');
  console.error('what makes it easy to ignore, and what let it run 37 days once already.');
  process.exit(1);
} catch (err) {
  console.error(`check-reproducible: the check itself failed: ${err && err.message}`);
  console.error('Treat this as unknown, never as a pass.');
  process.exit(2);
} finally {
  cleanup();
}
